function xorBytesIntoState(s, bytes, laneCount) {
  for (let i = 0; i < laneCount; i++) {
    const o = i * 8;
    s[2 * i] ^= bytes[o] | (bytes[o + 1] << 8) | (bytes[o + 2] << 16) | (bytes[o + 3] << 24);
    s[2 * i + 1] ^= bytes[o + 4] | (bytes[o + 5] << 8) | (bytes[o + 6] << 16) | (bytes[o + 7] << 24);
  }
}

const hexToBytes = (h) => {
  h = h.replace(/^0x/, "");
  const out = new Uint8Array(h.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(h.substr(2 * i, 2), 16);
  return out;
};
const word = (hex) => { const b = hexToBytes(hex.replace(/^0x/, "").padStart(64, "0")); return b; };

/**
 * Prepare a mining job. All inputs are 0x-hex strings (chainId may be a number).
 * Returns { mid, tail } where mid is the state after block 1 and tail is block 2's constant bytes.
 */
export function prepare({ domain, chainId, contract, anchorHash, miner, nonceHigh }) {
  const msg = new Uint8Array(192);
  msg.set(word(domain), 0);
  msg.set(word(BigInt(chainId).toString(16)), 32);
  msg.set(word(contract), 64);
  msg.set(word(anchorHash), 96);
  msg.set(word(miner), 128);
  msg.set(word(nonceHigh || "0"), 160);
  msg.fill(0, 184, 192); // the low 8 bytes of the nonce are written per attempt

  const mid = new Int32Array(50);
  xorBytesIntoState(mid, msg.subarray(0, 136), 17);
  keccakF(mid);

  const tail = new Uint8Array(136);            // block 2: bytes 136..191, then keccak padding
  tail.set(msg.subarray(136, 192), 0);
  tail[56] ^= 0x01;
  tail[135] ^= 0x80;
  const tailLanes = new Int32Array(34);
  xorBytesIntoState(tailLanes, tail, 17);
  return { mid, tailLanes, msg };
}

const bswap = (v) => ((v & 0xff) << 24) | ((v & 0xff00) << 8) | ((v >>> 8) & 0xff00) | (v >>> 24);

/**
 * Try `count` nonces starting at `start` (the low 64 bits of the nonce: hiWord:loWord).
 * Returns the first counter whose digest's top 64 bits are below targetTop (as [hi32, lo32] unsigned),
 * or -1. The caller verifies the full 256-bit comparison.
 */
export function search(job, hiWord, start, count, targetHi, targetLo) {
  const s = new Int32Array(50);
  const { mid, tailLanes } = job;
  // nonce low 8 bytes live in block-2 lane 6 (bytes 48..55), big-endian
  const laneLoFixed = bswap(hiWord);
  for (let n = 0; n < count; n++) {
    const ctr = (start + n) >>> 0;
    for (let i = 0; i < 34; i++) s[i] = mid[i] ^ tailLanes[i];
    for (let i = 34; i < 50; i++) s[i] = mid[i];
    s[12] ^= laneLoFixed;
    s[13] ^= bswap(ctr);
    keccakFast(s);
    // digest bytes 0..3 = low half of lane 0 (little-endian) -> top 32 bits of the uint256
    const top = bswap(s[0]) >>> 0;
    if (top < targetHi || (top === targetHi && (bswap(s[1]) >>> 0) < targetLo)) return ctr;
  }
  return -1;
}

/** Full digest for one nonce (hex), used to double-check a candidate before sending it. */
export function digestHex(job, hiWord, ctr) {
  const s = new Int32Array(50);
  for (let i = 0; i < 50; i++) s[i] = job.mid[i] ^ (i < 34 ? job.tailLanes[i] : 0);
  s[12] ^= bswap(hiWord);
  s[13] ^= bswap(ctr >>> 0);
  keccakF(s);
  let hex = "";
  for (let i = 0; i < 4; i++) {
    const lo = s[2 * i], hi = s[2 * i + 1];
    for (const v of [lo, hi]) for (let k = 0; k < 4; k++) hex += ((v >>> (8 * k)) & 0xff).toString(16).padStart(2, "0");
  }
  return "0x" + hex;
}

/** The uint256 nonce the contract will receive: nonceHigh's top 24 bytes, then hiWord, then ctr. */
export function nonceHex(nonceHigh, hiWord, ctr) {
  const top = (nonceHigh || "0").replace(/^0x/, "").padStart(64, "0").slice(0, 48);
  return "0x" + top + (hiWord >>> 0).toString(16).padStart(8, "0") + (ctr >>> 0).toString(16).padStart(8, "0");
}
