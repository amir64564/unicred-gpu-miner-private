// ARCAT miner core: keccak256 over the exact bytes the contract hashes, with a precomputed midstate.
//
// digest = keccak256(abi.encode(DOMAIN, chainId, contract, anchorHash, miner, nonce))  -> 192 bytes.
// keccak256 absorbs 136-byte blocks, so block 1 (bytes 0..135) never changes while mining a given
// anchor: we permute it once, keep that "midstate", and every attempt only runs the second permutation.
//
// Lanes are 64-bit, emulated with pairs of 32-bit ints: s[2*i] = low half, s[2*i+1] = high half.

const RC = [
  0x00000001, 0x00000000, 0x00008082, 0x00000000, 0x0000808a, 0x80000000, 0x80008000, 0x80000000,
  0x0000808b, 0x00000000, 0x80000001, 0x00000000, 0x80008081, 0x80000000, 0x00008009, 0x80000000,
  0x0000008a, 0x00000000, 0x00000088, 0x00000000, 0x80008009, 0x00000000, 0x8000000a, 0x00000000,
  0x8000808b, 0x00000000, 0x0000008b, 0x80000000, 0x00008089, 0x80000000, 0x00008003, 0x80000000,
  0x00008002, 0x80000000, 0x00000080, 0x80000000, 0x0000800a, 0x00000000, 0x8000000a, 0x80000000,
  0x80008081, 0x80000000, 0x00008080, 0x80000000, 0x80000001, 0x00000000, 0x80008008, 0x80000000,
];
// rho rotation for lane index x + 5y, and pi destination
const ROT = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39, 41, 45, 15, 21, 8, 18, 2, 61, 56, 14];
const PI = new Array(25);
for (let x = 0; x < 5; x++) for (let y = 0; y < 5; y++) PI[x + 5 * y] = y + 5 * ((2 * x + 3 * y) % 5);

const B = new Int32Array(50);
const C = new Int32Array(10);

/** keccak-f[1600] in place on a 50-int state. */
export function keccakF(s) {
  for (let round = 0; round < 24; round++) {
    // theta
    for (let x = 0; x < 5; x++) {
      C[2 * x] = s[2 * x] ^ s[2 * x + 10] ^ s[2 * x + 20] ^ s[2 * x + 30] ^ s[2 * x + 40];
      C[2 * x + 1] = s[2 * x + 1] ^ s[2 * x + 11] ^ s[2 * x + 21] ^ s[2 * x + 31] ^ s[2 * x + 41];
    }
    for (let x = 0; x < 5; x++) {
      const x1 = (x + 1) % 5, x4 = (x + 4) % 5;
      const lo = C[2 * x1], hi = C[2 * x1 + 1];
      const dlo = C[2 * x4] ^ ((lo << 1) | (hi >>> 31));
      const dhi = C[2 * x4 + 1] ^ ((hi << 1) | (lo >>> 31));
      for (let y = 0; y < 25; y += 5) {
        s[2 * (x + y)] ^= dlo;
        s[2 * (x + y) + 1] ^= dhi;
      }
    }
    // rho + pi
    for (let i = 0; i < 25; i++) {
      const lo = s[2 * i], hi = s[2 * i + 1], r = ROT[i], j = PI[i];
      if (r === 0) { B[2 * j] = lo; B[2 * j + 1] = hi; }
      else if (r < 32) { B[2 * j] = (lo << r) | (hi >>> (32 - r)); B[2 * j + 1] = (hi << r) | (lo >>> (32 - r)); }
      else if (r === 32) { B[2 * j] = hi; B[2 * j + 1] = lo; }
      else { const q = r - 32; B[2 * j] = (hi << q) | (lo >>> (32 - q)); B[2 * j + 1] = (lo << q) | (hi >>> (32 - q)); }
    }
    // chi
    for (let y = 0; y < 25; y += 5) {
      for (let x = 0; x < 5; x++) {
        const a = 2 * (x + y), b = 2 * (((x + 1) % 5) + y), c = 2 * (((x + 2) % 5) + y);
        s[a] = B[a] ^ (~B[b] & B[c]);
        s[a + 1] = B[a + 1] ^ (~B[b + 1] & B[c + 1]);
      }
    }
    // iota
    s[0] ^= RC[2 * round];
    s[1] ^= RC[2 * round + 1];
  }
}

